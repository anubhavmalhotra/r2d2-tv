"""Closed outcome vocabulary. No free text ever leaves the agent."""
from dataclasses import dataclass

STATES = ('verified', 'accepted', 'rejected', 'refused', 'unknown')

CODES = frozenset('''
REQUEST_NOT_ARMED REQUEST_EXPIRED AGENT_BUSY AGENT_PAUSED AUDIT_UNAVAILABLE
TRANSCRIPT_SCOPE MODEL_UNAVAILABLE MODEL_CONFIG TOOL_SCHEMA TOOL_DISABLED
RATE_LIMITED UNSUPPORTED_COMMAND NEGATED_COMMAND NOTHING_PENDING PENDING_CANCELLED
EXECUTION_UNCONFIRMED
CONFIRMATION_PENDING CONFIRMATION_DECLINED CONFIRMATION_EXPIRED
CONFIRMATION_SURFACE_UNAVAILABLE
BROWSER_NOT_OPENED BROWSER_NAVIGATION_ACCEPTED NAVIGATION_REJECTED NAVIGATION_UNCONFIRMED
BROWSER_HISTORY_ACCEPTED HISTORY_REJECTED HISTORY_UNCONFIRMED
BROWSER_MEDIA_VERIFIED BROWSER_MEDIA_NO_VIDEO MEDIA_REJECTED MEDIA_UNCONFIRMED
BROWSER_SESSION_ENDED END_REJECTED END_UNCONFIRMED BROWSER_STATUS_SHOWN
TV_CHANNEL_UNAVAILABLE TV_TOOL_UNAVAILABLE TV_PERMISSION_DENIED TV_APP_NOT_INSTALLED
TV_LAUNCH_REJECTED TV_FOREGROUND_VERIFIED TV_VOLUME_ACCEPTED TV_VOLUME_VERIFIED
TV_MUTE_VERIFIED TV_MEDIA_ACCEPTED TV_REQUEST_REJECTED TV_UNCONFIRMED TV_STATUS_SHOWN
DEEPLINK_UNQUALIFIED
HANDOFF_NOT_ARMED HANDOFF_PEER HANDOFF_SCHEMA HANDOFF_ATTEMPT HANDOFF_REPLAY HANDOFF_STALE
PARSE_MISMATCH RECEIPT_NOT_AUTHORITY
VOICE_WARMING_UP VOICE_UNAVAILABLE
'''.split())


class Refused(Exception):
    """Carries one fixed code. Its text is never user, page or model content."""
    def __init__(self, code):
        if code not in CODES:
            raise ValueError('REFUSAL_VOCABULARY')
        super().__init__(code)
        self.code = code

    def __str__(self):
        return self.code


@dataclass(frozen=True)
class Outcome:
    state: str
    code: str

    def __post_init__(self):
        if self.state not in STATES or self.code not in CODES:
            raise ValueError('OUTCOME_VOCABULARY')
