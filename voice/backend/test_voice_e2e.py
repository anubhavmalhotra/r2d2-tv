"""One utterance end to end across every voice UI surface, with real wire formats.

The resident's own signed phase pings (golden bytes regenerated by
voice/tv/test_resident_mic.js) go through Spark's real /voice-phase route into the
one VoiceStatus; the pipeline drives it through the real _UtteranceController,
AgentController event filter and StatusFeedback; Home reads the browser-key
long-poll; the viewer card crosses the real signed Manager/Trial channel into the
Trial mirror and its heartbeat reply bytes; the resident reads its receipt. Each
Home view is also checked by Home's own JavaScript validator. Synthetic data only:
no TV, model, network peer or real utterance.
"""
import functools
import importlib.machinery
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import threading
import time
from types import SimpleNamespace
import unittest
from unittest.mock import Mock, patch

from voice.backend.browser_channel import TrialControlHost, channel_pair, valid_card
from voice.backend.resident_utterance import _UtteranceController, resident_device_key
from voice.backend.test_resident_entry import BROWSER_KEY, KEY, Fixture
from voice.backend.voice_card_push import push_voice_card
from voice.backend.voice_status import ping_mac

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = json.loads((ROOT / 'voice/tv/test_voice_phase_golden.json').read_text())
# Heartbeat reply bytes this flow produces; spark/tests/test_viewer.js.in renders each one.
VIEWER_GOLDEN = ROOT / 'spark/tests/voice_card_golden.json.in'
HOST = [('Host', '192.0.2.10:4181')]
HOME_KEYS = ['v', 'seq', 'phase', 'ageMs', 'tone', 'word', 'headline', 'detail', 'badge', 'meter',
             'meterMs', 'dwellMs', 'mood', 'chip']
CARD_KEYS = HOME_KEYS[:-1] + ['echo']
SESSION = 'e' * 32
PRESS, SHORT = '0123456789abcdef', 'fedcba9876543210'


def view(seq, phase='idle', *, age=0, tone='ready', word='', headline='', detail='', badge=None, meter=None,
         meter_ms=None, dwell=None, mood='idle', chip='ready'):
    return dict(v=1, seq=seq, phase=phase, ageMs=age, tone=tone, word=word, headline=headline, detail=detail,
                badge=badge, meter=meter, meterMs=meter_ms, dwellMs=dwell, mood=mood, chip=chip)


def card(home, echo=None):
    value = {key: item for key, item in home.items() if key != 'chip'}
    value['echo'] = echo
    return value


@functools.lru_cache(maxsize=None)
def mirror_module():
    # Trial's mirror ships as spark/runtime/voice_card.py; its source has no template.
    path = ROOT / 'spark/runtime/voice_card.py.in'
    loader = importlib.machinery.SourceFileLoader('r2d2_e2e_voice_card', str(path))
    module = importlib.util.module_from_spec(importlib.util.spec_from_loader(loader.name, loader))
    loader.exec_module(module)
    return module


class Clock:
    def __init__(self): self.now = 7000.0
    def __call__(self): return self.now


class VoiceEndToEnd(Fixture):
    def setUp(self):
        super().setUp()
        self.owner = self.entry(); self.addCleanup(self.owner.close)
        self.owner.hook.note_tv_power = Mock()
        self.status = self.owner.voice_status
        # One shared synthetic clock makes ageMs exact; holds still use real time.
        self.clock = Clock()
        self.status.clock = self.clock
        self.status._at = self.clock()
        self.homes, self.cards, self.replies = [], [], []

    # -- wire helpers -------------------------------------------------------------
    def ping(self, raw):
        body = raw.encode('ascii')
        status, reply, _ = self.request(self.owner, method='POST', path='/' + KEY + '/voice-phase', body=body,
                                        headers=HOST + [('Content-Type', 'application/json'),
                                                        ('Content-Length', str(len(body)))])
        self.assertEqual(status, 200)
        return reply

    def home(self, since):
        status, body, head = self.request(self.owner, path='/' + BROWSER_KEY + '/voice/' + str(since),
                                          headers=HOST + [('Origin', 'null')])
        self.assertEqual(status, 200)
        self.assertIn(b'Access-Control-Allow-Origin: null', head)
        self.assertEqual(list(body), HOME_KEYS)
        self.assertLessEqual(len(json.dumps(body, separators=(',', ':')).encode('ascii')), 512)
        self.homes.append(body)
        return body

    def held_home(self, since, act):
        out = []
        thread = threading.Thread(target=lambda: out.append(self.home(since)))
        thread.start()
        end = time.monotonic() + 2
        while self.status._home_waiter is None and time.monotonic() < end:
            time.sleep(.005)
        self.assertIsNotNone(self.status._home_waiter, 'Home poll was not held')
        result = act()
        thread.join(3)
        self.assertFalse(thread.is_alive())
        return out[0], result

    def receipt(self, press):
        status, body, _ = self.request(self.owner, path='/' + KEY + '/voice-receipt/' + press, headers=HOST)
        self.assertEqual(status, 200)
        self.assertEqual(list(body), ['schema', 'press', 'done', 'toast', 'shown'])
        return body

    def viewer(self):
        """Trial side: the real channel host and mirror, and its /metrics reply bytes."""
        mirror = mirror_module().VoiceCard(clock=self.clock)
        client, sock = channel_pair(SESSION)
        def exchange(body):   # Trial.voice_card_exchange
            return mirror.exchange(body['card']) if type(body) is dict and set(body) == {'card'} else None
        host = TrialControlHost(sock, SimpleNamespace(lock=threading.RLock(), voice_card_exchange=exchange))
        thread = threading.Thread(target=host.serve, kwargs={'lifetime_s': 30}, daemon=True)
        thread.start()
        def stop():
            client.close(); host.close(); thread.join(1)
        self.addCleanup(stop)
        manager = SimpleNamespace(control_spawn=SimpleNamespace(current_client=lambda *, timeout_s: (SESSION, client)))
        def push():
            self.assertTrue(push_voice_card(manager, self.status))
        def heartbeat():
            data, seq = mirror.reply(False)   # exactly what Trial's /metrics handler writes
            self.assertTrue(data.isascii()); self.assertLessEqual(len(data), 1024)
            if seq is not None:
                mirror.mark_delivered(seq)
            value = json.loads(data)
            self.assertEqual(list(value), ['ok', 'voice'])
            if value['voice'] is not None:
                self.replies.append(data.decode('ascii'))
                # The signed channel canonicalizes key order; the viewer checks the key set.
                self.assertEqual(sorted(value['voice']), sorted(CARD_KEYS))
                self.assertTrue(valid_card(value['voice']) and mirror_module().valid_card(value['voice']))
                self.cards.append(value['voice'])
            return value
        return push, heartbeat, client, host

    def home_validator_accepts_all(self):
        node = shutil.which('node')
        if node is None:
            self.skipTest('node absent')
        script = ("const {voiceValue}=require(process.argv[1]);"
                  "const views=JSON.parse(require('fs').readFileSync(0,'utf8'));"
                  "process.stdout.write(JSON.stringify(views.map(v=>{try{return voiceValue(v);}catch(_){return null;}})));")
        raw = subprocess.run([node, '-e', script, str(ROOT / 'tv/home/core.js.in')], input=json.dumps(self.homes),
                             capture_output=True, text=True, timeout=20, check=True).stdout
        self.assertEqual(json.loads(raw), self.homes)

    # -- the utterance ------------------------------------------------------------
    def test_youtube_search_utterance_across_resident_spark_home_viewer_and_receipt(self):
        self.assertEqual(self.record()['tvCertificateSha256'], GOLDEN['tvCertificateSha256'])
        pings = GOLDEN['pings']
        push, heartbeat, client, host = self.viewer()
        # Resident /state heartbeat: readiness reaches the Home chip.
        with patch.object(type(self.owner.hook), 'state', new_callable=lambda: property(lambda hook: 'ready')):
            self.assertEqual(self.request(self.owner)[1], {'warm': 'ready', 'session': 'none', 'agent': 'ok'})
        self.assertEqual(self.home(0), view(2))
        push()
        self.assertEqual(heartbeat()['voice'], card(view(2)))

        # Hold the mic: Home's held poll wakes on the resident's signed ping.
        pressed = view(3, 'pressed', tone='work', word='GETTING READY', headline='One moment...',
                       detail='Keep holding the mic button.', mood='front')
        seen, reply = self.held_home(2, lambda: self.ping(pings[0]))
        self.assertEqual((seen, reply), (pressed, {'ok': True, 'surface': 'home'}))
        self.assertEqual(self.ping(pings[1]), {'ok': True, 'surface': 'home'})
        self.clock.now += .25
        self.assertEqual(self.home(3), view(4, 'listening', age=250, tone='listen', word='LISTENING',
                                            headline='Listening...', detail='Speak, then let go.', meter='hold',
                                            meter_ms=5499, mood='listening'))
        self.assertEqual(self.ping(pings[2]), {'ok': True, 'surface': 'home'})
        released = view(5, 'released', tone='work', word='THINKING', headline='Got it.', detail='Working on it...',
                        meter='sweep', mood='thinking')
        self.assertEqual(self.home(4), released)
        push()
        self.assertEqual(heartbeat()['voice'], card(released))

        # Spark: TLS upload binds the released press; arm and transcribe never regress it.
        token = self.status.begin_utterance()
        utterance = _UtteranceController(self.owner.helper.controller,
                                         SimpleNamespace(acquire=lambda: None, release=lambda: None),
                                         lambda: True, self.status, token)
        lease = utterance.arm()
        self.status.thinking(token)
        self.assertEqual(self.home(0), released)
        agent = self.owner.helper.controller.agent
        agent.events(lease, 'doing', {'tool': 'browser.youtube_search', 'slot': None})
        doing = view(6, 'doing', tone='work', word='ON IT', headline='Searching YouTube...', meter='sweep',
                     mood='thinking')
        self.assertEqual(self.home(5), doing)
        push()
        self.assertEqual(heartbeat()['voice'], card(doing))
        # The agent shows its outcome (echo staged, never published), then reports it.
        self.assertIs(self.owner.helper.controller.feedback.show(
            'BROWSER_NAVIGATION_ACCEPTED', 'browser_youtube', echo='lo-fi   music'), True)
        agent.events(lease, 'outcome', {'state': 'accepted', 'code': 'BROWSER_NAVIGATION_ACCEPTED', 'rule': None,
                                        'ttl': None, 'tool': 'browser.youtube_search', 'slot': None})
        self.owner.helper.controller.cancel(lease)
        self.status.outcome(token, 'accepted', 'BROWSER_NAVIGATION_ACCEPTED')   # before the TLS frame
        result = view(7, 'result', tone='sent', word='SENT', headline='Searching YouTube...', badge='sent',
                      dwell=4000)
        self.assertEqual(self.home(6), result)
        self.assertNotIn('lo-fi', json.dumps(self.homes))

        # Viewer: the card carries the echo; a written heartbeat reply is delivery.
        push()
        self.assertEqual(heartbeat()['voice'], card(result, echo='lo-fi music'))
        receipts = []
        thread = threading.Thread(target=lambda: receipts.append(self.receipt(PRESS)))
        thread.start()
        time.sleep(.1)
        self.assertTrue(thread.is_alive(), 'receipt should wait for a surface ack')
        push()   # reports the delivered seq back to Spark
        thread.join(2)
        self.assertEqual(receipts, [dict(schema=1, press=PRESS, done=True, toast=None, shown=True)])
        self.assertEqual((client.regular_requests, host.regular_requests, host.requested_at), (0, 0, None))

        # The receipt ages out with no other change: it takes one new seq, so Home's
        # held poll wakes on its own and the viewer card turns idle.
        idle, _ = self.held_home(7, lambda: setattr(self.clock, 'now', self.clock.now + 4.1))
        self.assertEqual(idle, view(8, age=4100))
        push()
        self.assertEqual(heartbeat()['voice'], card(view(8, age=4100)))

        # A second press too short to hear: the resident's own fault ping.
        self.assertEqual([self.ping(raw)['surface'] for raw in pings[3:]], ['home'] * 3)
        fault = view(11, 'result', tone='nothing', word='NOTHING DONE', headline='I didn’t hear anything.',
                     detail='Hold the mic button while you speak.', badge='nothing', dwell=5000)
        self.assertEqual(self.home(8), fault)
        push()
        self.assertEqual(heartbeat()['voice'], card(fault))
        push()
        self.assertEqual(self.receipt(SHORT), dict(schema=1, press=SHORT, done=True, toast=None, shown=True))
        self.home_validator_accepts_all()
        self.assertEqual([c['seq'] for c in self.cards], [2, 5, 6, 7, 8, 11])
        if os.environ.get('R2D2_GOLDEN_DUMP'):
            print(json.dumps(self.replies))
        else:
            self.assertEqual(self.replies, [row['reply'] for row in json.loads(VIEWER_GOLDEN.read_text())['replies']])

    def test_unseen_outcome_returns_its_toast_at_once(self):
        # No Home poll or viewer delivery within 3 s: the resident toasts Spark's copy.
        device, seq = resident_device_key(KEY, self.record()['tvCertificateSha256']), 0
        press = '5' * 16
        for phase in ('pressed', 'listening', 'released'):
            seq += 1
            row = dict(schema=1, boot='c' * 16, seq=seq, press=press, phase=phase, code=None,
                       deadlineMs=9199 if phase == 'listening' else None, cut=phase == 'released')
            self.assertEqual(self.ping(json.dumps(dict(row, mac=ping_mac(device, row)), separators=(',', ':'))),
                             {'ok': True, 'surface': 'other'})
        token = self.status.begin_utterance()
        self.status.armed(token)
        self.assertEqual(self.home(0)['detail'], 'That was the 9-second limit. Using what I heard.')
        self.clock.now += 3.1   # that Home read is now too old to count as visible
        self.status.doing('tv.volume', 'volume:up:2')
        self.status.agent_outcome('verified', 'TV_VOLUME_VERIFIED', 'tv.volume', 'volume:up:2')
        self.status.outcome(token, 'verified', 'TV_VOLUME_VERIFIED')
        began = time.monotonic()
        self.assertEqual(self.receipt(press), dict(schema=1, press=press, done=True, toast='Volume up 2', shown=False))
        self.assertLess(time.monotonic() - began, .5)
        self.assertEqual(self.home(0), view(self.status.home_view()['seq'], 'result', tone='done', word='DONE',
                                            headline='Turned the volume up 2.', badge='confirmed', dwell=4000,
                                            mood='verified', chip='starting'))
        self.home_validator_accepts_all()


